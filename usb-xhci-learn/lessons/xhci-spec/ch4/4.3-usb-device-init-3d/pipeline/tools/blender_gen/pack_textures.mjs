#!/usr/bin/env node
// pack_textures.mjs —— S6 纹理打包：manifest(web 段) → src/textures.gen.js（X43_TEXDATA 常量）+ 预算账
// 用法：node pack_textures.mjs [--dir pipeline/tools/blender_gen/out] [--out src/textures.gen.js]
// 消费分区：textureRequests（repeat/normalScale 元数据内置，尺寸来自 manifest）
// 下游：build.mjs（textures.gen.js 在场时注入引擎前；缺席=占位档回退）
// 预算：base64 总量硬门 ≤1.5MB（超限 exit 1，降级梯在 compress_textures.py 侧执行）
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const argv = process.argv;
const argOf = (n, d) => (argv.includes(n) ? argv[argv.indexOf(n) + 1] : d);
const D = argOf("--dir", join(HERE, "out"));
const OUT = argOf("--out", join(HERE, "..", "..", "..", "src", "textures.gen.js"));

// S6 注入元数据（占位档 repeat 语义调整：tex01 改 [1,1]——贴图按整面板设计，防螺丝点阵跨面裁切）
const META = {
  tex01: { repeat: [1, 1], normalScale: 0.7 },
  tex02: { repeat: [2, 1] },
  tex03: { repeat: [2, 1], normalScale: 0.65 },
  tex04: { repeat: [1, 1], normalScale: 0.5 },
  tex05: { repeat: [6, 1] },
  tex06: { repeat: [1, 1] },
  tex07: { repeat: [1, 1] },
  tex08: { repeat: [1, 1] },
  tex09: { repeat: [1, 1], normalScale: 0.8 },
  tex10: { repeat: [1, 1] },
  tex11: { repeat: [1, 1] },
  tex12: { repeat: [1, 1] },
};
// three.js 材质槽名映射（bake kind → material 属性名）
const SLOT = { albedo: "map", rough: "roughnessMap", normal: "normalMap", ao: "aoMap", emissive: "emissiveMap" };

const man = JSON.parse(readFileSync(join(D, "manifest.json"), "utf8"));
const b64 = (p) => readFileSync(join(D, p)).toString("base64");

const textures = {};
let total = 0;
for (const [tex, meta] of Object.entries(META)) {
  const web = man.web && man.web[tex];
  if (!web) throw new Error("manifest.web 缺 " + tex + "（先跑 compress_textures.py）");
  const entry = { repeat: meta.repeat };
  if (meta.normalScale != null) entry.normalScale = meta.normalScale;
  entry.maps = {};
  for (const [kind, slot] of Object.entries(SLOT)) {
    if (!web[kind]) continue;
    const dim = (man.textures[tex] && man.textures[tex][kind]) || {};
    const u = "data:" + web[kind].mime + ";base64," + b64(web[kind].file);
    total += u.length;
    entry.maps[slot] = { url: u, w: dim.w, h: dim.h, bytes: web[kind].bytes };
  }
  textures[tex] = entry;
}
let env = null;
if (man.env && man.web && man.web.env) {
  const u = "data:" + man.web.env.mime + ";base64," + b64(man.web.env.file);
  total += u.length;
  env = { url: u, w: man.env.w, h: man.env.h };
}
const HARD = 1536000;
const doc = {
  gen: "s6-blender",
  note: "GENERATED by pipeline/tools/blender_gen/{gen_textures,post_tile,compress_textures}.py + pack_textures.mjs — do not edit",
  textures,
  env,
};
const js = "/* ===== textures.gen.js（S6 生成件——X43_TEXDATA；由 blender_gen 工具链产出，勿手改） ===== */\n"
  + "const X43_TEXDATA = " + JSON.stringify(doc) + ";\n";
writeFileSync(OUT, js);
console.log("PACK tex=" + Object.keys(textures).length + " env=" + (env ? "yes" : "no") + " total_b64=" + total
  + " (" + (total / 1024).toFixed(0) + "KB) hard-gate=" + HARD + (total <= HARD ? " PASS" : " OVER"));
if (total > HARD) {
  console.error("PACK-BUDGET-OVER：压缩降级梯未达标，报主会话裁决砍项");
  process.exit(1);
}
console.log("PACK-DONE " + OUT);
