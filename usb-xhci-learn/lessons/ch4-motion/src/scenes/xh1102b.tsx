//  - SS/USB2 错误（L358-365, p194）：SS STALL TP→CC=Stall Error（L358-360）；
//    USB2 错误→CC=USB Transaction Error（L362-365）
//  - 中止（L367-372, p194）："All Control transfers begin with a Setup Stage
//    TD and end with a Status Stage TD. A Control transfer may be aborted
