// §4.11.2.2 Setup Stage, Data Stage, and Status Stage TRBs —— xHCI 1.2b
// p192-195（R12 批 C 大档支：控制三阶段一支讲透；Figure 4-14 语义重建、
// Table 4-7 讲两代表行全表归 landing）
// 判据（evidence/spec-411.txt，判据唯一事实源；行号=切片内行号）：
//  - 三阶段 1:1："At the USB packet level, a Control Transfer consists of
//    multiple transactions partitioned into stages: a setup stage, an
//    optional data stage, and a terminating status stage. The xHCI defines
//    the Setup Stage TRB, Data Stage TRB, and Status Stage TRB to provide a
//    1:1 mapping to the respective USB Control transfer stages."
//    （L143-147, p192）
//  - SETUP Data："Table 9-2 of the USB2 or USB3 specification defines the
//    format of the USB SETUP Data. The host is responsible for establishing
//    the values passed in the USB SETUP Data fields. Every USB Setup packet
//    is comprised of an eight byte USB SETUP Data structure."（L152-155,
//    p192）；Figure 4-14（L156-182）：bmRequestType/bRequest/wValue/wIndex/
//    wLength 映射进 Setup Stage TRB Parameter 组件
//  - 控制环 TD 构成（L183-204, p192）：环可含 Setup/Status TD、可选 Data
//    TD（L185-187）；Setup TD=单 Setup Stage TRB（L188-189）；Data TD=Data
//    Stage TRB 链 0..n Normal/Event Data TRB（L190-192）；Status TD=单
//    Status Stage TRB 可选链 Event Data TRB（L193-195）；一切控制传输须
//    Setup TD 后跟 Status TD、需要数据时由软件插 Data TD（L196-201）；
//    No-data 控制传输=Setup 与 Status 之间无 Data TD（L202-204）
//  - Setup TRB 细则（L211-215, p192）："A Setup Stage TRB shall contain
//    immediate data (IDT flag = ‘1’), its Parameter fields shall contain
//    the 8-byte USB SETUP Data, … and its Length field shall be set to ‘8’."
//  - DIR 一致性（L222-228, p192-193）："System software is responsible for
//    ensuring that the Direction (DIR) flag of the Data Stage and Status
//    Stage TRBs are consistent with the USB SETUP Data defined
//    bmRequestType:Data Transfer Direction (DTD) flag and wLength field.
//    Refer to Table 4-7 for mapping. … No more than one Data Stage TD may
//    be defined between a pair of Setup and Status Stage TDs."
//  - Table 4-7（L229-256, p193）代表两行：Host-to-device 且 wLength>0 →
//    TRT=0/OUT Data Stage/Data DIR=OUT/Status DIR=IN（L243-247）；
//    Device-to-host 且 wLength>0 → IN Data Stage/Data DIR=IN/Status DIR=OUT
//    （L253-256）
//  - Status DIR Note（L257-262）："The Direction (DIR) flag in the Status
//    Stage TRB indicates the direction of the control transfer
//    acknowledgement."；Data DIR Note（L263-267）："The Direction (DIR) flag
//    in the Data Stage TRB defines the transfer direction for all TRBs in
//    the Data Stage TD."
//  - 续链与总长（L268-283, p193-194）："If the data associated with a Data
//    Stage TD is not contiguous, then additional Normal TRBs shall be
//    chained in a Data Stage TD."；"System software is responsible for
//    ensuring that the total data length defined by a Data Stage TD (that
//    is, the sum of the Length fields of the Data Stage TRB and all Normal
//    TRBs) is equal to wLength. Note that communicating with some
//    non-compliant devices may require violating this rule. The transfer
//    lengths managed by the xHC depend strictly on the TRB Length fields."
//  - Status 事件 CC（L285-297, p194）："The Transfer Event generated by a
//    Status Stage TRB shall report a Success, Stall Error, or other error
//    Completion Code."；Success=设备完成命令可受新命令（L288-291）；Stall
//    Error=设备有错（L293-295）+ "Software shall provide a timeout for all
//    control operations and abort them using a Stop Endpoint Command if the
//    operation times out."（L296-297）
//  - Busy Note（L298-301）："If a USB device is still processing the command
//    when the Status Stage TD is executed, the device will return a Busy
//    response. The xHC shall wait indefinitely for a Success, Stall Error or
//    other error response from device for the Status stage."
//  - xHC NOT check 六条件（L302-325, p194）：wLength=‘0’ 而有 Data TD（L311）/
//    wLength=‘0’ 而无 Status TD（L313-314）/ wLength>‘0’ 而无 Data TD
//    （L316-317）/ Data TD 总量≠wLength（L319）/ Data DIR 不符 Table 4-7
//    （L321-322）/ Status DIR 不符 Table 4-7（L324-325）；脚注38（L330-332）：
//    TRT 严格指示 Data TD 的在场与方向、wLength 应被 xHC 忽略
//  - NOT required+查则报（L326-346, p194）："The xHC is NOT required to
//    check for the following Control transfer error conditions. … However
//    if the xHC does check for these conditions it shall generate a Transfer
//    Event for the TRB that the error was detected on with the Completion
//    Code set to TRB Error."；条件=Status TD 不跟 Data TD（L343-344）/
//    Setup Stage TRB Length≠8（L346）
//  - SET_ADDRESS 陷阱（L348-356, p194）："The xHC shall inspect the bRequest
//    field in Setup Stage TRBs for a SET_ADDRESS request code and the
//    bmRequestType field for Data Transfer Direction (DTD) = Host-to-device,
