// §4.11.3 Event TRBs + 4.11.3.1 Transfer Event TRB —— xHCI 1.2b p201-202
//（R12 批 C 中档支）
// 判据（evidence/spec-411.txt，判据唯一事实源；行号=切片内行号）：
//  - ED 定义（L677-679+L685, p201，跨 PAGE 201 标拼接）："Event TRBs
//    shall be found on an Event Ring. A Work Item on an Event Ring is called
//    an Event Descriptor (ED). An ED shall be comprised of only one … TRB
//    data structure. This section describes the operational characteristics
//    of the event related TRBs."
//  - 生产者/消费者（L687-688）："The xHC is the producer of all Event TRBs
//    and system software is the consumer."
//  - 用途（L689-691）："Event TRBs are used to report events associated with
//    the Command Ring and Transfer Rings, as well as a variety of other host
//    controller related events (Port Status Change, Bandwidth Requests, etc.)."
//  - 字段依赖（L692-695）："The field definitions of the Parameter, Length,
//    and the high word of the Control components of Event TRBs are all Event
//    Type Dependent. Refer to the specific Event definitions below for more
//    information on these definitions. The Event Type field shall define the
//    contents of the Event Type Dependent fields."
//  - 环约束（L696-700）："The Event Type field shall indicate Event Ring TRB
//    Types as defined in Table 6-91. Any Event Type may be found on the
//    Primary Event Ring. Only Transfer, Bandwidth Request, and Device
//    Notification Events may be found on a secondary Event Ring. Refer to
//    section 4.9.4.3 for a discussion of Primary and Secondary Event Rings."
//  - IMPLEMENTATION NOTE（L701-706）："The xHC shall ensure that all Dwords in
//    an Event TRB are updated before it toggles the Cycle (C) bit in Dword 3.
//    An xHC implementation may update all 4 Dwords of the Event TRB as an
//    atomic (single DMA) operation, or if it updates the Event TRB Dwords as
//    discrete operations, then it shall update Dword 3 (toggling the Cycle
//    bit) last."
//  - Transfer Event 生成三条件（L709-716, p201）："Transfer Event TRB
//    generation shall only occur under the following conditions: If the
//    Interrupt On Completion (IOC) flag is set. When a short transfer occurs
//    during the execution of a Transfer TRB and the Interrupt-on-Short Packet
//    (ISP) flag is set. If an error occurs during the execution of a Transfer
//    TRB."
//  - 不可归因错误（L717-719）："Several transfer related errors may be
//    detected that cannot be attributed to a specific TRB, for example, Ring
//    Overrun, Ring Underrun, etc. In these cases, the xHC shall set the TRB
//    Pointer to ‘0’ and software shall treat it as invalid."
//  - 推进逐 IOC（L720-724）："When the data transfer associated with a
//    Transfer TRB completes, a Transfer Event shall be generated by the xHC
//    if the TRB IOC or ISP flags are set to ‘1’, or if an error occurs on the
//    transfer associated with the TRB. And while advancing to the end the
//    current TD after generating this event, each Transfer TRB encountered
//    with its IOC flag set to ‘1’ shall generate a Transfer Event."
//  - CC/Length 继承（L725-728）："The Condition Code of the “current”
//    Transfer Event shall be set to the value of the Condition Code in the
//    original Transfer Event, and the TRB Transfer Length of the current
//    Transfer Event should be set to value of the TRB Transfer Length field
//    in the original Transfer Event."
import {makeScene2D, Txt} from '@motion-canvas/2d';
import {createRef, Vector2, waitFor} from '@motion-canvas/core';
import {C, FONT, TLx, TLy} from '../lib/theme';
import {
  buildStage,
  lanesIn,
  makeCard,
  cardIn,
  makeRing,
  makeChip,
  makeNote,
  flash,
  CardApi,
  StageApi,
  RingApi,
} from '../lib/parts';

export default makeScene2D(function* (view) {
  view.fill(C.bg);

  /* ===== 片头 ===== */
  const t1 = createRef<Txt>();
  const t2 = createRef<Txt>();
  const t3 = createRef<Txt>();
  view.add(
    <>
      <Txt ref={t1} text={'§4.11.3'} x={0} y={TLy(350)} fontFamily={FONT.mono}
        fontSize={120} fontWeight={800} fill={C.hc} />
      <Txt ref={t2} text={'Event TRBs'} x={0} y={TLy(490)} fontFamily={FONT.sans}
        fontSize={84} fontWeight={800} fill={C.ink} />
      <Txt ref={t3} text={'事件 TRB 与 Transfer Event · xHCI 规范第 4 章 · p201–202'}
        x={0} y={TLy(610)} fontFamily={FONT.sans} fontSize={34} fill={C.dim} />
    </>,
  );
  t1().opacity(1);
  t2().opacity(1);
  yield* waitFor(0.35);
  t3().opacity(1);
  yield* waitFor(0.35);
  yield* waitFor(0.6);
  t1().opacity(0);
  t2().opacity(0);
  t3().opacity(0);
  yield* waitFor(0.3);
  t1().remove(); t2().remove(); t3().remove();

  /* ===== 舞台 ===== */
  const stage: StageApi = buildStage(view, {
    section: '§4.11.3',
    zh: 'Event TRBs',
    en: '事件 TRB 与 Transfer Event · 规范第 4 章',
    cite: 'xHCI 1.2b §4.11.3 p201–202',
  });
  yield* lanesIn(stage);

  /* 事件环（主位）+ 传输环（事件来源演示） */
  const evt: RingApi = makeRing(view, {
    y: 470, zh: '事件环 Event Ring', en: '',
    note: 'xHC 生产 ED', tint: C.evt, x0: 760, x1: 1450, n: 10,
  });
  const xfer: RingApi = makeRing(view, {
    y: 655, zh: '传输环 Transfer Ring', en: '',
    note: '软件生产 · 事件来源', tint: C.driver, x0: 760, x1: 1450, n: 10,
  });
  evt.group().opacity(1);
  xfer.group().opacity(1);
  yield* waitFor(0.2);
  evt.markLink();
  yield* waitFor(0.25);

  /* ===== ① ED 定义与生产消费反转 ===== */
  const q1 = makeChip(
    view,
    '"Event TRBs shall be found on an Event Ring. A Work Item on an Event Ring is called an Event Descriptor (ED). An ED shall be comprised of only one … TRB data structure. … The xHC is the producer of all Event TRBs and system software is the consumer." — §4.11.3 p201',
    {x: TLx(1090), y: TLy(265), w: 1300, tint: C.evt, size: 15},
  );
  yield* stage.say('事件环工作项=ED=单支事件 TRB；生产消费反转。', '① / 9');
  q1().opacity(0.95);
  yield* evt.fill(0, 'ED', C.evt);
  yield* evt.enqTo(1);
  yield* waitFor(0.3);
  yield* waitFor(3.1);
  q1().opacity(0);
  yield* waitFor(0.25);

  /* ===== ② 事件用途 ===== */
  const q2 = makeChip(
    view,
    '"Event TRBs are used to report events associated with the Command Ring and Transfer Rings, as well as a variety of other host controller related events (Port Status Change, Bandwidth Requests, etc.)." — §4.11.3 p201',
    {x: TLx(1090), y: TLy(265), w: 1300, tint: C.hc, size: 16},
  );
  yield* stage.say('命令环/传输环/主机控制器杂项事件都走事件环。', '② / 9');
  q2().opacity(0.95);
  yield* waitFor(0.3);
  yield* waitFor(3.9);
  q2().opacity(0);
  yield* waitFor(0.25);

  /* ===== ③ 字段=Event Type 依赖 ===== */
  const q3 = makeChip(
    view,
    '"The field definitions of the Parameter, Length, and the high word of the Control components of Event TRBs are all Event Type Dependent. … The Event Type field shall define the contents of the Event Type Dependent fields. The Event Type field shall indicate Event Ring TRB Types as defined in Table 6-91." — §4.11.3 p201',
    {x: TLx(1090), y: TLy(265), w: 1300, tint: C.driver, size: 14},
  );
  yield* stage.say('Parameter/Length/Control 高字随事件型定义。', '③ / 9');
  q3().opacity(0.95);
  yield* waitFor(0.3);
  yield* waitFor(3.6);
  q3().opacity(0);
  yield* waitFor(0.25);

  /* ===== ④ 主/副事件环准入 ===== */
  const q4 = makeChip(
    view,
    '"Any Event Type may be found on the Primary Event Ring. Only Transfer, Bandwidth Request, and Device Notification Events may be found on a secondary Event Ring." — §4.11.3 p201',
    {x: TLx(1090), y: TLy(265), w: 1300, tint: C.hc, size: 16},
  );
  const n4 = makeNote(
    view,
    [
      '副事件环只收三类（L697-699）：Transfer / Bandwidth Request /',
      'Device Notification；主事件环来者不拒——主/副语义见 §4.9.4.3。',
    ],
    {x: TLx(1300), y: TLy(285), w: 1040, tint: C.driver},
  );
  yield* stage.say('主环全类型；副环只准三类事件。', '④ / 9');
  q4().opacity(0.95);
  yield* waitFor(0.3);
  yield* waitFor(1.2);
  q4().opacity(0);
  yield* waitFor(0.2);
  n4().opacity(0.9);
  yield* waitFor(0.3);
  yield* waitFor(1.5);
  n4().opacity(0);
  yield* waitFor(0.25);

  /* ===== ⑤ IMPLEMENTATION NOTE：Dword 3 最后 ===== */
  const q5 = makeChip(
    view,
    '"The xHC shall ensure that all Dwords in an Event TRB are updated before it toggles the Cycle (C) bit in Dword 3. An xHC implementation may update all 4 Dwords of the Event TRB as an atomic (single DMA) operation, or if it updates the Event TRB Dwords as discrete operations, then it shall update Dword 3 (toggling the Cycle bit) last." — §4.11.3 IMPLEMENTATION NOTE p201',
    {x: TLx(1090), y: TLy(265), w: 1300, tint: C.warn, size: 13},
  );
  yield* stage.say('实现注记：C 位最后翻转——软件见 C 变即全字段有效。', '⑤ / 9');
  q5().opacity(0.95);
  yield* flash(evt.group, 1);
  yield* waitFor(0.3);
  yield* waitFor(4.0);
  q5().opacity(0);
  yield* waitFor(0.25);

  /* ===== ⑥ Transfer Event 生成三条件 ===== */
  const q6 = makeChip(
    view,
    '"Transfer Event TRB generation shall only occur under the following conditions: … If the Interrupt On Completion (IOC) flag is set. … When a short transfer occurs during the execution of a Transfer TRB and the Interrupt-on-Short Packet (ISP) flag is set. … If an error occurs during the execution of a Transfer TRB." — §4.11.3.1 p201',
    {x: TLx(1090), y: TLy(265), w: 1300, tint: C.evt, size: 14},
  );
  yield* stage.say('Transfer Event 只认三条件：IOC/短包+ISP/错误。', '⑥ / 9');
  q6().opacity(0.95);
  yield* xfer.fill(0, 'TRB·IOC', C.driver);
  yield* xfer.enqTo(1);
  yield* xfer.deqTo(0, 0.4);
  yield* xfer.consume(0);
  yield* evt.fill(1, 'TransferEvt', C.evt);
  yield* evt.enqTo(2);
  yield* waitFor(0.3);
  yield* waitFor(2.4);
  q6().opacity(0);
  yield* waitFor(0.25);

  /* ===== ⑦ 不可归因错误：TRB Pointer=‘0’ ===== */
  const q7 = makeChip(
    view,
    '"Several transfer related errors may be detected that cannot be attributed to a specific TRB, for example, Ring Overrun, Ring Underrun, etc. In these cases, the xHC shall set the TRB Pointer to ‘0’ and software shall treat it as invalid." — §4.11.3.1 p201',
    {x: TLx(1090), y: TLy(265), w: 1300, tint: C.warn, size: 16},
  );
  yield* stage.say('环级错误无处归因——TRB Pointer 置 0 作废。', '⑦ / 9');
  q7().opacity(0.95);
  yield* waitFor(0.3);
  yield* waitFor(3.4);
  q7().opacity(0);
  yield* waitFor(0.25);

  /* ===== ⑧ 推进中逐 IOC 生成 ===== */
  const q8 = makeChip(
    view,
    '"When the data transfer associated with a Transfer TRB completes, a Transfer Event shall be generated by the xHC if the TRB IOC or ISP flags are set to ‘1’, or if an error occurs on the transfer associated with the TRB. And while advancing to the end the current TD after generating this event, each Transfer TRB encountered with its IOC flag set to ‘1’ shall generate a Transfer Event." — §4.11.3.1 p201',
    {x: TLx(1090), y: TLy(265), w: 1300, tint: C.driver, size: 13},
  );
  yield* stage.say('推进到 TD 尾途中，逢 IOC=1 的 TRB 逐支生成。', '⑧ / 9');
  q8().opacity(0.95);
  yield* xfer.fill(1, 'TRB·IOC', C.driver);
  yield* xfer.enqTo(2);
  yield* xfer.deqTo(1, 0.4);
  yield* xfer.consume(1);
  yield* evt.fill(2, 'TransferEvt', C.evt);
  yield* evt.enqTo(3);
  yield* waitFor(0.3);
  yield* waitFor(1.9);
  q8().opacity(0);
  yield* waitFor(0.25);

  /* ===== ⑨ 后续事件 CC/Length 继承 ===== */
  const q9 = makeChip(
    view,
    '"The Condition Code of the “current” Transfer Event shall be set to the value of the Condition Code in the original Transfer Event, and the TRB Transfer Length of the current Transfer Event should be set to value of the TRB Transfer Length field in the original Transfer Event." — §4.11.3.1 p201-202',
    {x: TLx(1090), y: TLy(265), w: 1300, tint: C.hc, size: 15},
  );
  yield* stage.say('同 TD 后续事件：CC 与 Length 承接首事件。', '⑨ / 9');
  q9().opacity(0.95);
  yield* flash(evt.group, 1);
  yield* waitFor(0.3);
  yield* waitFor(3.0);
  q9().opacity(0);
  yield* waitFor(0.25);

  /* ===== 收口 ===== */
  const sum: CardApi = makeCard({
    title: '§4.11.3 Event TRBs',
    rows: [
      {k: 'ED', v: '事件环工作项=单支事件 TRB 数据结构'},
      {k: '反转', v: 'xHC 生产 · 软件消费 · 字段随 Event Type 定义'},
      {k: '生成', v: 'IOC / 短包+ISP / 错误 三条件 · 环级错 Ptr=0'},
      {k: '继承', v: '推进途中逐 IOC 生成 · CC/Length 承接首事件'},
      {k: '下一支', v: '§4.11.4 Command TRBs'},
    ],
    tint: C.hc,
    w: 980,
    rowSize: 20,
  });
  view.add(sum.node);
  evt.group().opacity(0);
  xfer.group().opacity(0);
  yield* stage.say('事件面讲透——下一支：Command TRB 格式族。', '完');
  yield* cardIn(sum, new Vector2(TLx(960), TLy(840)));
  yield* waitFor(3.2);
  sum.ref().opacity(0);
  stage.caption().opacity(0);
  yield* waitFor(0.4);
});
